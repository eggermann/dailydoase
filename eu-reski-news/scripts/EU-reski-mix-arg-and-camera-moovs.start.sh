#!/bin/sh
set -eu

SCRIPT_DIR="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
WORKTREE_ROOT="$(git -C "$SCRIPT_DIR/../.." rev-parse --show-toplevel)"
COMMON_GIT_DIR="$(git -C "$WORKTREE_ROOT" rev-parse --path-format=absolute --git-common-dir)"
MAIN_REPO_ROOT="$(dirname "$COMMON_GIT_DIR")"

NEWS_PROFILE="${NEWS_PROFILE:-EU-RESKI exhibition mix}"
NEWS_NEWS_DIR="${NEWS_NEWS_DIR:-$WORKTREE_ROOT/eu-reski-news/news/A}"
NEWS_OUTPUT_DIR="${NEWS_OUTPUT_DIR:-$WORKTREE_ROOT/eu-reski-news/GENERATIONS/news/exhibition}"
NEWS_SETTINGS_SEARCH_DIR="${NEWS_SETTINGS_SEARCH_DIR:-$WORKTREE_ROOT/eu-reski-news/GENERATIONS/news}"
NEWS_REFRESH_INTERVAL_MS="${NEWS_REFRESH_INTERVAL_MS:-86400000}"
NEWS_REFRESH_CHECK_MS="${NEWS_REFRESH_CHECK_MS:-900000}"
NEWS_REFRESH_RETRY_MS="${NEWS_REFRESH_RETRY_MS:-900000}"
EXHIBITION_FIRST_LAST_GLUE="${EXHIBITION_FIRST_LAST_GLUE:-1}"
EXHIBITION_GLUE_DURATION_PATTERN="${EXHIBITION_GLUE_DURATION_PATTERN:-9,5,7,5,8}"
EXHIBITION_FRAME_OFFSET_SECONDS="${EXHIBITION_FRAME_OFFSET_SECONDS:-0.25}"
EXHIBITION_FADE_SECONDS="${EXHIBITION_FADE_SECONDS:-0.25}"
EXHIBITION_RANDOM_BRIDGE_THRESHOLD="${EXHIBITION_RANDOM_BRIDGE_THRESHOLD:-0.7}"

ENV_FILE="${NEWS_ENV_FILE:-$MAIN_REPO_ROOT/.env}"
if [ ! -f "$ENV_FILE" ] && [ -f "$WORKTREE_ROOT/.env" ]; then ENV_FILE="$WORKTREE_ROOT/.env"; fi
if [ ! -f "$ENV_FILE" ]; then
  echo "Missing environment file: $ENV_FILE" >&2
  echo 'Set NEWS_ENV_FILE or put .env in main repository.' >&2
  exit 2
fi

export NEWS_PROFILE NEWS_NEWS_DIR NEWS_OUTPUT_DIR NEWS_SETTINGS_SEARCH_DIR
export NEWS_REFRESH_INTERVAL_MS NEWS_REFRESH_CHECK_MS NEWS_REFRESH_RETRY_MS
export EXHIBITION_FIRST_LAST_GLUE EXHIBITION_GLUE_DURATION_PATTERN
export EXHIBITION_FRAME_OFFSET_SECONDS EXHIBITION_FADE_SECONDS EXHIBITION_RANDOM_BRIDGE_THRESHOLD

printf '[%s] news: %s\n' "$NEWS_PROFILE" "$NEWS_NEWS_DIR"
printf '[%s] output: %s\n' "$NEWS_PROFILE" "$NEWS_OUTPUT_DIR"
printf '[%s] refresh: every %s hours; Jev-ranked, linear article order\n' "$NEWS_PROFILE" "$(awk "BEGIN { printf \"%.1f\", $NEWS_REFRESH_INTERVAL_MS / 3600000 }")"
printf '[%s] glue: %s · first/last frame offset %s s · sparse film keeps draws > %s\n' \
  "$NEWS_PROFILE" "$EXHIBITION_GLUE_DURATION_PATTERN" "$EXHIBITION_FRAME_OFFSET_SECONDS" "$EXHIBITION_RANDOM_BRIDGE_THRESHOLD"

exec node --env-file="$ENV_FILE" "$SCRIPT_DIR/exhibition-runner.mjs" "$@"
